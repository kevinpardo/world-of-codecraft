"""Sync the approved "Héroïque MMO" heroes into the mod. Re-runnable: copies whatever exists now.

  <venv with Pillow>/bin/python tools/sync_heroes.py [HEROES_DIR]
  (HEROES_DIR defaults to $HEROES, else the scratchpad's village-art/heroes/1)

Reads (never writes) HEROES_DIR/assets/<race>-<class>.png + meta.json (30 standing sprites) and
HEROES_DIR/anim/frames/<race>-<class>/<anim>/NN.png + anim/frames/meta.json (only the heroes done so far).
Writes art/heros/<race>-<class>/ in the mod:
  stand.png, stand-n.png                 the standing sprite, day and night-graded
  <anim>/NN.png, <anim>/NN-n.png         every frame, day and night-graded
  walk_dr/, walk_ul/                     mirrors of walk_dl / walk_ur (Herdr can't flip an image)
and regenerates heros-data.js, the index of what exists (sizes, anchors, frame counts, fps, walk speed).
A hero listed in the anim meta but with missing frames falls back to its standing sprite."""
import json, os, shutil, sys
import numpy as np
from PIL import Image

MOD = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "mods", "world-of-codecraft")
DEFAULT = "/private/tmp/claude-501/-Users-kevin/2580f5fa-13bc-4b93-bdc8-9d5b9f07275a/scratchpad/village-art/heroes/1"
SRC = (sys.argv[1] if len(sys.argv) > 1 else None) or os.environ.get("HEROES") or DEFAULT
OUT = os.path.join(MOD, "art", "heros")
ANIMS = ["idle", "walk_dl", "walk_ur", "work", "rest"]
MIRROR = {"walk_dr": "walk_dl", "walk_ul": "walk_ur"}


def night(im):
    """The world's night grade (compose3: rgb*(0.20,0.25,0.46) + blue lift), softened so units stay readable."""
    a = np.asarray(im.convert("RGBA")).astype(np.float32)
    rgb = a[..., :3]
    lum = rgb @ np.array([0.3, 0.55, 0.15], np.float32)
    nc = rgb * np.array([0.20, 0.25, 0.46]) + lum[..., None] * np.array([0.05, 0.07, 0.16]) + np.array([6, 9, 26])
    out = nc * 0.62 + rgb * np.array([0.42, 0.46, 0.62]) * 0.38
    a[..., :3] = np.clip(out, 0, 255)
    return Image.fromarray(a.astype(np.uint8), "RGBA")


def put(im, path):
    im.save(path + ".png", optimize=True)
    night(im).save(path + "-n.png", optimize=True)


def main():
    ameta = json.load(open(os.path.join(SRC, "assets", "meta.json")))
    fdir = os.path.join(SRC, "anim", "frames")
    fmeta = {}
    if os.path.exists(os.path.join(fdir, "meta.json")):
        fmeta = json.load(open(os.path.join(fdir, "meta.json")))
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)
    index, animated = {}, []
    for key, m in sorted(ameta.items()):
        if key.startswith("_"):
            continue
        src = os.path.join(SRC, "assets", key + ".png")
        if not os.path.exists(src):
            continue
        d = os.path.join(OUT, key)
        os.makedirs(d)
        put(Image.open(src).convert("RGBA"), os.path.join(d, "stand"))
        entry = {"stand": {k: m[k] for k in ("w", "h", "ax", "ay")}, "anims": {}}
        fm = fmeta.get(key)
        if fm:
            for an in ANIMS:
                am = fm.get("anims", {}).get(an)
                if not am:
                    continue
                files = [os.path.join(fdir, key, an, f"{i:02d}.png") for i in range(am["frames"])]
                if not all(os.path.exists(f) for f in files):
                    continue  # incomplete: skip this anim (fallback in code)
                os.makedirs(os.path.join(d, an))
                frames = [Image.open(f).convert("RGBA") for f in files]
                for i, im in enumerate(frames):
                    put(im, os.path.join(d, an, f"{i:02d}"))
                info = {k: am[k] for k in ("w", "h", "ax", "ay", "fps")}
                info["n"] = am["frames"]
                entry["anims"][an] = info
                for mname, base in MIRROR.items():
                    if base != an:
                        continue
                    os.makedirs(os.path.join(d, mname))
                    for i, im in enumerate(frames):
                        put(im.transpose(Image.FLIP_LEFT_RIGHT), os.path.join(d, mname, f"{i:02d}"))
                    mi = dict(info)
                    mi["ax"] = am["w"] - 1 - am["ax"]
                    entry["anims"][mname] = mi
            if fm.get("walk_speed_px_per_s"):
                entry["speed"] = fm["walk_speed_px_per_s"]
        if entry["anims"]:
            animated.append(key)
        index[key] = entry
    with open(os.path.join(MOD, "heros-data.js"), "w") as f:
        f.write("// Generated by tools/sync_heroes.py: the heroes and animations present in art/heros/. Re-run to update.\n")
        f.write("// Per hero: stand {w,h,ax,ay} (logical px, feet anchor); anims {name: {n, fps, w, h, ax, ay}}; speed (px/s).\n")
        f.write("export const HEROES = {\n" + ",\n".join(f"  {json.dumps(k)}: {json.dumps(v)}" for k, v in index.items()) + "\n};\n")
    print(f"{len(index)} heroes, animated: {', '.join(animated) or 'none'}")


if __name__ == "__main__":
    main()
